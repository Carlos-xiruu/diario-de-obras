import { expect, test } from '@playwright/test'

test('bloqueia visitante e permite login local', async ({ page }) => {
  await page.goto('/')
  await expect(page).toHaveURL(/\/login/)
  await page.getByPlaceholder('Email').fill('e2e-admin@local.test')
  await page.getByPlaceholder('Senha').fill('SenhaE2E!123')
  await page.getByRole('button', { name: 'ENTRAR' }).click()
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByText('CANTEIROS ATIVOS')).toBeVisible()
})

test('fluxo local de obra, catálogo, diário e dashboard', async ({ page }) => {
  await page.goto('/login')
  await page.getByPlaceholder('Email').fill('e2e-admin@local.test')
  await page.getByPlaceholder('Senha').fill('SenhaE2E!123')
  await page.getByRole('button', { name: 'ENTRAR' }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.goto('/nova-obra')
  await page.getByPlaceholder('Ex: Galpão Logístico Lote 02').fill('Obra E2E Local')
  await page.getByPlaceholder('Ex: Jaraguá do Sul, SC').fill('Teste')
  await page.getByRole('button', { name: 'Cadastrar Obra' }).click()
  const heading = page.getByRole('heading', { name: 'Obra E2E Local' }).last()
  await expect(heading).toBeVisible()
  const card = heading.locator('../..')
  await card.getByRole('link', { name: 'PEÇAS' }).click()
  await page.locator('input[type=file]').setInputFiles('fixtures/referencias/Aedifica CT2574 - Controle Diario Montagem.xlsx')
  await page.getByRole('button', { name: 'Validar planilha' }).click()
  await expect(page.getByText(/Prévia: 284 grupos/)).toBeVisible({ timeout: 30_000 })
  await page.getByRole('button', { name: 'Confirmar importação' }).click()
  await expect(page.getByText('Histórico de importações')).toBeVisible({ timeout: 30_000 })
  const obraUrl = page.url().replace('/pecas', '/dashboard')
  await page.goto(obraUrl)
  await expect(page.getByText('Dashboard da obra')).toBeVisible()
  await expect(page.getByLabel('Pavimento')).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('link', { name: 'Novo diário' })).toBeVisible()
})
